"""Make a lesson the active one:  python tools/use.py 1.2

Writes lessons/CURRENT and regenerates the two tiny files the studio reads the lesson from
(studio/src/current.ts, studio/src/currentLesson.ts). If the lesson has no studio files yet, it
scaffolds them: empty timings/clips data and a placeholder scene map that shows each segment's
narration, so `npm run studio` works before any scene is designed.
"""
import json
import os
import sys

from common import ROOT, STUDIO, Paths, load_json

CURRENT_TS = '''// GENERATED by tools/use.py — do not edit. Active lesson: {lid}
export const LESSON = "{lid}";
export {{ default as scriptJson }} from "../../lessons/{lid}/script.json";
export {{ default as timingsJson }} from "./data/{lid}/timings.json";
export {{ default as clipsJson }} from "./data/{lid}/clips.json";
'''

CURRENT_LESSON_TS = '''// GENERATED by tools/use.py — do not edit. Active lesson: {lid}
export {{ segments }} from "./lessons/{lid}";
'''

STUB_INDEX = '''import React from "react";
import script from "../../../../lessons/{lid}/script.json";
import {{ SegmentDef, StubScene }} from "../../scenes/Common";

/**
 * Scene map for Lesson {lid}. One entry per segment of lessons/{lid}/script.json, in order.
 * Replace each StubScene with a real scene: a ClipScene over lab footage, or a card from
 * ../../scenes/Cards. The finished reference is studio/src/lessons/1.1/index.tsx.
 */
export const segments: SegmentDef[] = script.segments.map((s) => ({{
  id: s.id,
  render: () => <StubScene id={{s.id}} chapter={{s.chapter}} text={{s.text}} />,
}}));
'''


def use(lid: str, quiet: bool = False) -> Paths:
    P = Paths(lid)
    if not os.path.exists(P.script):
        sys.exit(f'lessons/{lid}/script.json not found. Create the lesson first: python tools/new_lesson.py {lid} "<title>"')
    script = load_json(P.script)
    if script["lesson"]["number"] != lid:
        sys.exit(f"lessons/{lid}/script.json says lesson.number = {script['lesson']['number']!r}; expected {lid!r}")

    os.makedirs(P.data, exist_ok=True)
    for f in (P.timings, P.clips_json):
        if not os.path.exists(f):
            json.dump({}, open(f, "w", encoding="utf-8"))
    os.makedirs(P.scenes, exist_ok=True)
    index = os.path.join(P.scenes, "index.tsx")
    if not os.path.exists(index):
        open(index, "w", encoding="utf-8", newline="\n").write(STUB_INDEX.format(lid=lid))
        if not quiet:
            print(f"scaffolded placeholder scene map: studio/src/lessons/{lid}/index.tsx")
    for d in (P.audio, P.clips, P.out):
        os.makedirs(d, exist_ok=True)

    open(os.path.join(STUDIO, "src", "current.ts"), "w", encoding="utf-8", newline="\n").write(CURRENT_TS.format(lid=lid))
    open(os.path.join(STUDIO, "src", "currentLesson.ts"), "w", encoding="utf-8", newline="\n").write(CURRENT_LESSON_TS.format(lid=lid))
    open(os.path.join(ROOT, "lessons", "CURRENT"), "w", encoding="utf-8", newline="\n").write(lid + "\n")
    if not quiet:
        n = len(script["segments"])
        print(f"active lesson: {lid}  ({script['lesson']['title']}, {n} segments)")
    return P


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    use(sys.argv[1])
